function trend(base: { usefulness: number; hallucination: number; usage: number }) {
  return Array.from({ length: 8 }, (_, i) => ({
    date: `Wk ${i + 1}`,
    usefulness: Math.max(0, Math.min(100, base.usefulness + (Math.sin(i) * 4))),
    hallucination: Math.max(0, base.hallucination + (Math.cos(i) * 1.2)),
    usage: Math.max(0, base.usage + i * 35 + (Math.random() * 50 - 25)),
  }));
}

